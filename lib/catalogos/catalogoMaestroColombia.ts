/**
 * Normaliza un texto para búsqueda insensible a tildes, mayúsculas y espacios repetidos.
 */
export function normalizarTextoBusqueda(texto: string): string {
  return texto
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Retorna todos los procedimientos del catálogo pertenecientes a una vertical.
 */
export function listarCatalogoPorVertical(
  vertical: VerticalCatalogo
): ProcedimientoCatalogoMaestro[] {
  return CATALOGO_MAESTRO_COLOMBIA.filter((item) => item.vertical === vertical);
}

/**
 * Retorna el pack rápido (top 8–10 procedimientos populares) de una vertical para onboarding.
 */
export function obtenerPackPopularPorVertical(
  vertical: VerticalCatalogo
): ProcedimientoCatalogoMaestro[] {
  return CATALOGO_MAESTRO_COLOMBIA.filter(
    (item) => item.vertical === vertical && item.popular
  );
}

/**
 * Busca procedimientos por nombre, categoría, alias locales en Colombia o descripción,
 * insensible a tildes y mayúsculas, opcionalmente acotado a una vertical.
 */
export function buscarEnCatalogoMaestro(
  query: string,
  vertical?: VerticalCatalogo
): ProcedimientoCatalogoMaestro[] {
  const universo = vertical
    ? listarCatalogoPorVertical(vertical)
    : [...CATALOGO_MAESTRO_COLOMBIA];

  const consulta = normalizarTextoBusqueda(query);
  if (!consulta) return universo;

  const terminos = consulta.split(' ').filter(Boolean);
  const puntuados: Array<{ item: ProcedimientoCatalogoMaestro; score: number }> = [];

  for (const item of universo) {
    const nombreNorm = normalizarTextoBusqueda(item.nombre);
    const categoriaNorm = normalizarTextoBusqueda(item.categoria);
    const descNorm = normalizarTextoBusqueda(item.descripcion_corta);
    const idNorm = normalizarTextoBusqueda(item.id);
    const aliasesNorm = item.alias_busqueda.map(normalizarTextoBusqueda);

    const textoCompleto = [nombreNorm, categoriaNorm, ...aliasesNorm, descNorm, idNorm].join(' ');
    const coincideTodos = terminos.every((t) => textoCompleto.includes(t));
    if (!coincideTodos) continue;

    let score = 0;
    if (nombreNorm === consulta || aliasesNorm.includes(consulta)) score += 100;
    else if (nombreNorm.startsWith(consulta)) score += 70;
    else if (nombreNorm.includes(consulta)) score += 50;
    else if (aliasesNorm.some((a) => a.includes(consulta))) score += 45;
    else if (categoriaNorm.includes(consulta)) score += 30;
    else score += 15;

    if (item.popular) score += 5;

    puntuados.push({ item, score });
  }

  puntuados.sort((a, b) => b.score - a.score || a.item.nombre.localeCompare(b.item.nombre, 'es'));
  return puntuados.map((p) => p.item);
}
